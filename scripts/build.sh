#!/usr/bin/env bash
# Build the kernel and package it into a GPT disk image with a FAT32 EFI System Partition.
#   scripts/build.sh            normal build
#   FEATURES=x scripts/build.sh          build with cargo feature(s) enabled
#   NOVA_CMDLINE="nova.test=ud" scripts/build.sh   bake a kernel command line into the image
source "$(dirname "$0")/common.sh"
mkdir -p "$LOGS"
BUILD_LOG="$LOGS/build.log"
: > "$BUILD_LOG"

if [[ ",${FEATURES:-}," == *,linux-drivers,* ]]; then
    "$ROOT/scripts/build-linux.sh" || fail "Linux driver objects failed"
fi
log "Building kernel ($PROFILE${FEATURES:+, features: $FEATURES})"
cargo_args=(build --manifest-path "$KERNEL_DIR/Cargo.toml")
[[ "$PROFILE" == release ]] && cargo_args+=(--release)
[[ -n "${FEATURES:-}" ]] && cargo_args+=(--features "$FEATURES")
if ! (cd "$KERNEL_DIR" && cargo "${cargo_args[@]}") 2>&1 | tee -a "$BUILD_LOG"; then
    fail "cargo build failed (log: $BUILD_LOG)"
fi
[[ -f "$KERNEL_ELF" ]] || fail "kernel ELF not found at $KERNEL_ELF"

# User programs: plain C/C++ compiled for Linux x86-64 and linked statically; Nova
# runs them through its Linux system call layer (kernel/src/linux.rs).
log "Building user programs (static C/C++)"
mkdir -p "$USERLAND_OUT"
for src in "$USERLAND_SRC"/*.c "$USERLAND_SRC"/*.cpp; do
    [[ -f "$src" ]] || continue
    name="$(basename "${src%.*}")"
    case "$src" in
        *.c)   cc="${CC:-gcc}";  extra=(-lm) ;;
        *.cpp) cc="${CXX:-g++}"; extra=() ;;
    esac
    if ! "$cc" -static -O2 -Wall -o "$USERLAND_OUT/$name" "$src" "${extra[@]}" >>"$BUILD_LOG" 2>&1; then
        fail "compiling $src failed (log: $BUILD_LOG)"
    fi
    strip "$USERLAND_OUT/$name"
done

# 32-bit (i386) programs (userland/compat32/): Nova runs them in compatibility mode.
if compgen -G "$USERLAND_SRC/compat32/*.c" >/dev/null; then
    log "Building 32-bit user programs (static)"
    for src in "$USERLAND_SRC"/compat32/*.c; do
        name="$(basename "${src%.*}")"
        "${CC:-gcc}" -m32 -static -O2 -Wall -o "$USERLAND_OUT/$name" "$src" -lm >>"$BUILD_LOG" 2>&1 || fail "compiling $src failed (32-bit; needs lib32-glibc; log: $BUILD_LOG)"
        strip "$USERLAND_OUT/$name"
    done
fi

# Dynamically linked programs (userland/dynamic/) run with the host's dynamic loader
# and shared libraries, which are collected into a small sysroot shipped alongside.
SYSROOT="$BUILD/sysroot"
rm -rf "$SYSROOT"
mkdir -p "$SYSROOT"
# Home screen artwork (assets/home/, generated images; see assets/home/README.md).
mkdir -p "$SYSROOT/usr/share/nova/home"
cp "$ROOT"/assets/home/*.png "$SYSROOT/usr/share/nova/home/"
mkdir -p "$SYSROOT/usr/share/nova/icons"
cp "$ROOT"/assets/icons/*.png "$SYSROOT/usr/share/nova/icons/"
mkdir -p "$SYSROOT/usr/share/nova/glyphs"
cp "$ROOT"/assets/glyphs/*.png "$SYSROOT/usr/share/nova/glyphs/"
# The desktop's UI font (Noto Sans, SIL Open Font License), rendered by kernel/src/font.rs.
mkdir -p "$SYSROOT/usr/share/fonts/noto"
for f in NotoSans-Regular.ttf NotoSans-Bold.ttf; do
    src="$(fc-match -f '%{file}' "Noto Sans:style=${f#NotoSans-}" 2>/dev/null)"
    [[ -f "/usr/share/fonts/noto/$f" ]] && src="/usr/share/fonts/noto/$f"
    if [[ "$(basename "${src:-}")" == "$f" ]]; then cp -L "$src" "$SYSROOT/usr/share/fonts/noto/$f"; else log "warning: UI font $f not found (install Noto Sans); the desktop falls back to the bitmap font"; fi
done
# The terminal and code font: Adwaita Mono (SIL Open Font License), else DejaVu Sans Mono.
mkdir -p "$SYSROOT/usr/share/fonts/mono"
for style in Regular Bold; do
    for src in "/usr/share/fonts/Adwaita/AdwaitaMono-$style.ttf" "/usr/share/fonts/TTF/DejaVuSansMono${style/Regular/}.ttf"; do
        if [[ -f "$src" ]]; then cp -L "$src" "$SYSROOT/usr/share/fonts/mono/Mono-$style.ttf"; break; fi
    done
done
# Shields filter lists (scripts/fetch-filters.sh), if downloaded.
if compgen -G "$BUILD/filters/*.txt" >/dev/null; then
    mkdir -p "$SYSROOT/usr/share/nova/shields"
    cp "$BUILD"/filters/*.txt "$SYSROOT/usr/share/nova/shields/"
fi
for src in "$USERLAND_SRC"/dynamic/*.c "$USERLAND_SRC"/dynamic/*.cpp; do
    [[ -f "$src" ]] || continue
    name="$(basename "${src%.*}")"
    case "$src" in
        *.c)   cc="${CC:-gcc}";  extra=(-lm) ;;
        *.cpp) cc="${CXX:-g++}"; extra=() ;;
    esac
    "$cc" -O2 -Wall -o "$USERLAND_OUT/$name" "$src" "${extra[@]}" >>"$BUILD_LOG" 2>&1 || fail "compiling $src failed (log: $BUILD_LOG)"
    strip "$USERLAND_OUT/$name"
    interp="$(readelf -l "$USERLAND_OUT/$name" | sed -n 's/.*Requesting program interpreter: \(.*\)]/\1/p')"
    for lib in "$interp" $(ldd "$USERLAND_OUT/$name" | awk '/=> \//{print $3}'); do
        [[ -n "$lib" ]] || continue
        mkdir -p "$SYSROOT$(dirname "$lib")"
        cp -L "$lib" "$SYSROOT$lib"
    done
done
# Wayland clients (userland/wayland/): libwayland-client and xdg-shell code generated by
# wayland-scanner, if the host has them.
if compgen -G "$USERLAND_SRC/wayland/*.c" >/dev/null && command -v wayland-scanner >/dev/null && [[ -f /usr/share/wayland-protocols/stable/xdg-shell/xdg-shell.xml ]]; then
    gen="$BUILD/wayland-gen"
    mkdir -p "$gen"
    wayland-scanner client-header /usr/share/wayland-protocols/stable/xdg-shell/xdg-shell.xml "$gen/xdg-shell-client-protocol.h"
    wayland-scanner private-code /usr/share/wayland-protocols/stable/xdg-shell/xdg-shell.xml "$gen/xdg-shell-protocol.c"
    for src in "$USERLAND_SRC"/wayland/*.c; do
        name="$(basename "${src%.*}")"
        "${CC:-gcc}" -O2 -Wall -I"$gen" -o "$USERLAND_OUT/$name" "$src" "$gen/xdg-shell-protocol.c" -lwayland-client >>"$BUILD_LOG" 2>&1 || fail "compiling $src failed (needs libwayland; log: $BUILD_LOG)"
        strip "$USERLAND_OUT/$name"
        for lib in $(ldd "$USERLAND_OUT/$name" | awk '/=> \//{print $3}'); do
            mkdir -p "$SYSROOT$(dirname "$lib")"
            cp -L "$lib" "$SYSROOT$lib"
        done
    done
fi
# PulseAudio clients (userland/pulse/): libpulse-simple, if the host has it; plus the
# host's pactl, to inspect Nova's sound server (sinks, server info) with the real library.
if compgen -G "$USERLAND_SRC/pulse/*.c" >/dev/null && [[ -f /usr/include/pulse/simple.h ]]; then
    for src in "$USERLAND_SRC"/pulse/*.c; do
        name="$(basename "${src%.*}")"
        "${CC:-gcc}" -O2 -Wall -o "$USERLAND_OUT/$name" "$src" -lpulse-simple -lpulse -lm >>"$BUILD_LOG" 2>&1 || fail "compiling $src failed (needs libpulse; log: $BUILD_LOG)"
        strip "$USERLAND_OUT/$name"
    done
    [[ -x /usr/bin/pactl ]] && cp /usr/bin/pactl "$USERLAND_OUT/pactl"
    for prog in "$USERLAND_OUT"/patone "$USERLAND_OUT"/pactl; do
        [[ -f "$prog" ]] || continue
        for lib in $(ldd "$prog" | awk '/=> \//{print $3}'); do
            mkdir -p "$SYSROOT$(dirname "$lib")"
            cp -L "$lib" "$SYSROOT$lib"
        done
    done
fi
# X11 clients (userland/x11/): Xlib, if the host has it.
if compgen -G "$USERLAND_SRC/x11/*.c" >/dev/null && [[ -f /usr/include/X11/Xlib.h ]]; then
    for src in "$USERLAND_SRC"/x11/*.c; do
        name="$(basename "${src%.*}")"
        "${CC:-gcc}" -O2 -Wall -o "$USERLAND_OUT/$name" "$src" -lX11 >>"$BUILD_LOG" 2>&1 || fail "compiling $src failed (needs libX11; log: $BUILD_LOG)"
        strip "$USERLAND_OUT/$name"
        for lib in $(ldd "$USERLAND_OUT/$name" | awk '/=> \//{print $3}'); do
            mkdir -p "$SYSROOT$(dirname "$lib")"
            cp -L "$lib" "$SYSROOT$lib"
        done
    done
fi
# Dynamically linked 32-bit programs: the host's 32-bit loader (/lib/ld-linux.so.2) and
# libraries (lib32-glibc) go into the sysroot the same way.
for src in "$USERLAND_SRC"/compat32/dynamic/*.c; do
    [[ -f "$src" ]] || continue
    name="$(basename "${src%.*}")"
    "${CC:-gcc}" -m32 -O2 -Wall -o "$USERLAND_OUT/$name" "$src" -lm >>"$BUILD_LOG" 2>&1 || fail "compiling $src failed (32-bit; log: $BUILD_LOG)"
    strip "$USERLAND_OUT/$name"
    interp="$(readelf -l "$USERLAND_OUT/$name" | sed -n 's/.*Requesting program interpreter: \(.*\)]/\1/p')"
    for lib in "$interp" $(ldd "$USERLAND_OUT/$name" | awk '/=> \//{print $3}'); do
        [[ -n "$lib" ]] || continue
        mkdir -p "$SYSROOT$(dirname "$lib")"
        cp -L "$lib" "$SYSROOT$lib"
    done
done
# bubblewrap (the container tool Steam's pressure-vessel uses), if the host has it: the
# test for mount namespaces runs the host's binary and libraries unmodified.
if [[ -x /usr/bin/bwrap ]]; then
    for f in /usr/bin/bwrap $(ldd /usr/bin/bwrap | awk '/=> \//{print $3}'); do
        mkdir -p "$SYSROOT$(dirname "$f")"
        cp -L "$f" "$SYSROOT$f"
    done
fi
# Xwayland (an X server that draws through Wayland: X11 programs such as Steam get a
# display on Nova's compositor), with xkbcomp and the XKB layouts it compiles keymaps
# with, if the host has them.
if [[ -x /usr/bin/Xwayland && -x /usr/bin/xkbcomp ]]; then
    for f in /usr/bin/Xwayland /usr/bin/xkbcomp $(ldd /usr/bin/Xwayland /usr/bin/xkbcomp | awk '/=> \//{print $3}' | sort -u); do
        mkdir -p "$SYSROOT$(dirname "$f")"
        cp -L "$f" "$SYSROOT$f"
    done
    mkdir -p "$SYSROOT/usr/share/X11" "$SYSROOT/usr/lib/xorg"
    cp -rL /usr/share/X11/xkb "$SYSROOT/usr/share/X11/"
    [[ -f /usr/lib/xorg/protocol.txt ]] && cp /usr/lib/xorg/protocol.txt "$SYSROOT/usr/lib/xorg/"
fi
# GNU bash (Steam's launcher scripts need bash), /usr/bin/env, and the system's CA
# certificates for TLS, from the host.
if [[ -x /usr/bin/bash ]]; then
    for f in /usr/bin/bash $(ldd /usr/bin/bash | awk '/=> \//{print $3}'); do
        mkdir -p "$SYSROOT$(dirname "$f")"
        cp -L "$f" "$SYSROOT$f"
    done
fi
if [[ -f /etc/ssl/certs/ca-certificates.crt ]]; then
    mkdir -p "$SYSROOT/etc/ssl/certs"
    cp -L /etc/ssl/certs/ca-certificates.crt "$SYSROOT/etc/ssl/certs/"
fi
# Firmware for the Linux drivers (FEATURES=linux-drivers): the Realtek NICs' rtl_nic
# files, from the host's linux-firmware package (redistributable binaries, copied into the
# image only, never into the repository). r8169 loads them with request_firmware().
if [[ ",${FEATURES:-}," == *,linux-drivers,* && -d /usr/lib/firmware/rtl_nic ]]; then
    mkdir -p "$SYSROOT/usr/lib/firmware/rtl_nic"
    for f in /usr/lib/firmware/rtl_nic/*; do
        case "$f" in
            *.zst) zstd -qdcf "$f" > "$SYSROOT/usr/lib/firmware/rtl_nic/$(basename "${f%.zst}")" ;;
            *.xz) xz -dc "$f" > "$SYSROOT/usr/lib/firmware/rtl_nic/$(basename "${f%.xz}")" ;;
            *) cp "$f" "$SYSROOT/usr/lib/firmware/rtl_nic/" ;;
        esac
    done
    log "Including Realtek NIC firmware ($(ls "$SYSROOT/usr/lib/firmware/rtl_nic" | wc -l) files)"
fi
# amdgpu's firmware for the GPUs Nova is brought up on: sienna_cichlid (Navi 21: RX 6800,
# 6800 XT, 6900 XT) and navy_flounder (Navi 22: RX 6700 XT). Override with
# NOVA_AMDGPU_FIRMWARE="name ...". Symbolic links (shared images) are followed.
if [[ ",${FEATURES:-}," == *,linux-drivers,* && -d /usr/lib/firmware/amdgpu ]]; then
    mkdir -p "$SYSROOT/usr/lib/firmware/amdgpu"
    for chip in ${NOVA_AMDGPU_FIRMWARE:-sienna_cichlid navy_flounder}; do
        for f in /usr/lib/firmware/amdgpu/"$chip"_*; do
            [[ -e "$f" ]] || continue
            case "$f" in
                *.zst) zstd -qdcf "$f" > "$SYSROOT/usr/lib/firmware/amdgpu/$(basename "${f%.zst}")" ;;
                *.xz) xz -dc "$f" > "$SYSROOT/usr/lib/firmware/amdgpu/$(basename "${f%.xz}")" ;;
                *) cp -L "$f" "$SYSROOT/usr/lib/firmware/amdgpu/" ;;
            esac
        done
    done
    log "Including amdgpu firmware ($(ls "$SYSROOT/usr/lib/firmware/amdgpu" | wc -l) files: ${NOVA_AMDGPU_FIRMWARE:-sienna_cichlid navy_flounder})"
fi

# PulseAudio clients (Steam): each connection reserves a shared memory pool (64 MiB by
# default), which Nova's server never uses (audio comes over the socket), and Steam's
# 32-bit client could run out of address space. Keep the pools small; never autospawn.
mkdir -p "$SYSROOT/etc/pulse"
printf 'shm-size-bytes = 262144\nautospawn = no\n' > "$SYSROOT/etc/pulse/client.conf"
# The rest of glibc (64- and 32-bit): libraries that older programs and Steam's runtime
# link (libdl, librt, libpthread are stubs in today's glibc), and /bin/bash.
for dir in /usr/lib /usr/lib32; do
    for lib in libc.so.6 libdl.so.2 librt.so.1 libpthread.so.0 libutil.so.1 libresolv.so.2 libanl.so.1 libm.so.6 \
               libnss_files.so.2 libnss_dns.so.2 libgcc_s.so.1 libstdc++.so.6 libz.so.1 libnsl.so.1 libnsl.so.3; do
        [[ -f "$dir/$lib" ]] && { mkdir -p "$SYSROOT$dir"; cp -L "$dir/$lib" "$SYSROOT$dir/$lib"; }
    done
done
[[ -f /usr/lib32/ld-linux.so.2 ]] && { mkdir -p "$SYSROOT/usr/lib32" "$SYSROOT/lib"; cp -L /usr/lib32/ld-linux.so.2 "$SYSROOT/usr/lib32/"; [[ -e "$SYSROOT/lib/ld-linux.so.2" ]] || cp -L /usr/lib32/ld-linux.so.2 "$SYSROOT/lib/"; }
[[ -x "$SYSROOT/usr/bin/bash" ]] && { mkdir -p "$SYSROOT/bin"; ln -sf ../usr/bin/bash "$SYSROOT/bin/bash"; }
# glibc's ldd (a bash script; Steam checks its libraries with it) and the loader paths it
# names.
if [[ -f /usr/bin/ldd ]]; then
    cp /usr/bin/ldd "$SYSROOT/usr/bin/ldd"
    [[ -f /usr/lib32/ld-linux.so.2 && ! -e "$SYSROOT/usr/lib/ld-linux.so.2" ]] && { mkdir -p "$SYSROOT/usr/lib"; ln -s ../lib32/ld-linux.so.2 "$SYSROOT/usr/lib/ld-linux.so.2"; }
fi
# ldconfig (Steam's runtime lists the system libraries with it), its configuration, and the
# compiled locales (the host's locale-archive).
if [[ -x /usr/bin/ldconfig ]]; then
    mkdir -p "$SYSROOT/sbin" "$SYSROOT/usr/bin" "$SYSROOT/etc"
    cp -L /usr/bin/ldconfig "$SYSROOT/usr/bin/ldconfig"
    ln -sf ../usr/bin/ldconfig "$SYSROOT/sbin/ldconfig"
    [[ -f /etc/ld.so.conf ]] && cp /etc/ld.so.conf "$SYSROOT/etc/"
    [[ -d /etc/ld.so.conf.d ]] && cp -rL /etc/ld.so.conf.d "$SYSROOT/etc/"
fi
[[ -f /usr/lib/locale/locale-archive ]] && { mkdir -p "$SYSROOT/usr/lib/locale"; cp /usr/lib/locale/locale-archive "$SYSROOT/usr/lib/locale/"; }
# Copy files into the sysroot with every library ldd resolves for them; symbolic links
# stay links (shared data in the image).
copy_with_deps() {
    local f lib
    for f in "$@"; do
        [[ -e "$f" ]] || continue
        mkdir -p "$SYSROOT$(dirname "$f")"
        if [[ -L "$f" ]]; then
            cp -P "$f" "$SYSROOT$f"
            copy_with_deps "$(readlink -f "$f")"
            continue
        fi
        [[ -e "$SYSROOT$f" ]] || cp "$f" "$SYSROOT$f"
        for lib in $(ldd "$f" 2>/dev/null | awk '/=> \//{print $3}'); do
            [[ -e "$SYSROOT$lib" ]] || copy_with_deps "$lib"
        done
    done
}
# NOVA_STEAM=1: the host's OpenGL stacks (libglvnd + Mesa with its software rasterizer,
# about 200 MB each), for Steam. 32-bit programs (steamui.so) link libGL, and Xwayland
# offers GLX through Mesa's swrast driver; the graphics driver always comes from the
# system, not from Steam's runtime.
if [[ "${NOVA_STEAM:-0}" == 1 && -f /usr/lib/libGL.so.1 ]]; then
    copy_with_deps /usr/lib/libGL.so.1 /usr/lib/libGLX.so.0 /usr/lib/libGLdispatch.so.0 /usr/lib/libGLX_mesa.so.0 \
        /usr/lib/libEGL.so.1 /usr/lib/libEGL_mesa.so.0 /usr/lib/libgbm.so.1 /usr/lib/dri/swrast_dri.so /usr/lib/dri/kms_swrast_dri.so
fi
if [[ "${NOVA_STEAM:-0}" == 1 && -f /usr/lib32/libGL.so.1 ]]; then
    copy_with_deps /usr/lib32/libGL.so.1 /usr/lib32/libGLX.so.0 /usr/lib32/libGLdispatch.so.0 /usr/lib32/libGLX_mesa.so.0 \
        /usr/lib32/libEGL.so.1 /usr/lib32/libEGL_mesa.so.0 /usr/lib32/libva.so.2 /usr/lib32/libdrm.so.2 \
        /usr/lib32/dri/swrast_dri.so /usr/lib32/dri/kms_swrast_dri.so
    [[ -d /usr/share/glvnd ]] && { mkdir -p "$SYSROOT/usr/share"; cp -r /usr/share/glvnd "$SYSROOT/usr/share/"; }
fi
# Steam's launcher and bootstrap (Valve's proprietary redistributable), if the host has the
# steam package: only into this local image, never into the repository.
if [[ -f /usr/lib/steam/bootstraplinux_ubuntu12_32.tar.xz && -f /usr/lib/steam/bin_steam.sh ]]; then
    mkdir -p "$SYSROOT/usr/lib/steam" "$SYSROOT/usr/bin"
    cp /usr/lib/steam/bin_steam.sh /usr/lib/steam/bootstraplinux_ubuntu12_32.tar.xz "$SYSROOT/usr/lib/steam/"
    ln -sf bin_steam.sh "$SYSROOT/usr/lib/steam/steam"
    ln -sf ../lib/steam/bin_steam.sh "$SYSROOT/usr/bin/steam"
fi
# The Chromium engine (scripts/fetch-chromium.sh), if downloaded: its libraries too.
CHROMIUM="$BUILD/chromium/chrome-headless-shell-linux64"
if [[ -x "$CHROMIUM/chrome-headless-shell" ]]; then
    log "Including Chromium $(cat "$BUILD/chromium/VERSION" 2>/dev/null) and its shared libraries"
    # NSS loads its crypto module with dlopen, so ldd does not list it.
    extra=()
    for l in /usr/lib/libsoftokn3.so /usr/lib/libfreeblpriv3.so /usr/lib/libfreebl3.so; do [[ -f "$l" ]] && extra+=("$l"); done
    for lib in $(ldd "$CHROMIUM/chrome-headless-shell" "${extra[@]}" | awk '/=> \//{print $3}') "${extra[@]}"; do
        mkdir -p "$SYSROOT$(dirname "$lib")"
        cp -L "$lib" "$SYSROOT$lib"
    done
    mkdir -p "$SYSROOT/opt"
    cp -r "$CHROMIUM" "$SYSROOT/opt/chromium"
    # Fonts for web pages (Liberation and Noto, SIL Open Font License) and fontconfig's
    # configuration: Latin, Greek, Cyrillic, Arabic, Hebrew, Indic, Thai, CJK, symbols, emoji.
    for d in /usr/share/fonts/liberation /etc/fonts; do
        [[ -d "$d" ]] && { mkdir -p "$SYSROOT$(dirname "$d")"; cp -rL "$d" "$SYSROOT$d"; }
    done
    for f in noto/NotoSans-Regular.ttf noto/NotoSans-Bold.ttf noto/NotoSansArabic-Regular.ttf noto/NotoSansArmenian-Regular.ttf \
             noto/NotoSansBengali-Regular.ttf noto/NotoSansDevanagari-Regular.ttf noto/NotoSansEthiopic-Regular.ttf \
             noto/NotoSansGeorgian-Regular.ttf noto/NotoSansHebrew-Regular.ttf noto/NotoSansTamil-Regular.ttf \
             noto/NotoSansThai-Regular.ttf noto/NotoSansSymbols-Regular.ttf noto/NotoSansSymbols2-Regular.ttf \
             noto/NotoColorEmoji.ttf noto-cjk/NotoSansCJK-Regular.ttc; do
        [[ -f "/usr/share/fonts/$f" ]] && { mkdir -p "$SYSROOT/usr/share/fonts/$(dirname "$f")"; cp -L "/usr/share/fonts/$f" "$SYSROOT/usr/share/fonts/$f"; }
    done
fi
# GNU readlink, realpath, tar, xz and gzip (scripts use options BusyBox lacks, e.g. readlink
# -e or tar --checkpoint, as Steam's runtime setup does), from the
# host; BusyBox provides the other tools.
for tool in readlink realpath tar xz gzip; do
    if [[ -x "/usr/bin/$tool" ]]; then
        mkdir -p "$SYSROOT/bin"
        cp -L "/usr/bin/$tool" "$SYSROOT/bin/$tool"
        for lib in $(ldd "/usr/bin/$tool" | awk '/=> \//{print $3}'); do
            mkdir -p "$SYSROOT$(dirname "$lib")"
            cp -L "$lib" "$SYSROOT$lib"
        done
    fi
done
# Nova's lsof (userland/lsof.c) instead of BusyBox's, which ignores -i: Steam runs
# "lsof -i TCP@addr" to check who is at the other end of its UI's local connection.
mkdir -p "$SYSROOT/bin"
rm -f "$SYSROOT/bin/lsof"
cp "$USERLAND_OUT/lsof" "$SYSROOT/bin/lsof"

# BusyBox (scripts/fetch-busybox.sh), if built: bin/busybox plus one link per tool.
if [[ -x "$BUILD/busybox/busybox" ]]; then
    log "Including BusyBox $(cat "$BUILD/busybox/VERSION") ($(wc -l < "$BUILD/busybox/applets") tools)"
    mkdir -p "$SYSROOT/bin"
    cp "$BUILD/busybox/busybox" "$SYSROOT/bin/busybox"
    while read -r tool; do
        [[ -n "$tool" && "$tool" != busybox && ! -e "$SYSROOT/bin/$tool" ]] && ln -s busybox "$SYSROOT/bin/$tool"
    done < "$BUILD/busybox/applets"
    # Scripts start with #!/usr/bin/env.
    mkdir -p "$SYSROOT/usr/bin"
    [[ -e "$SYSROOT/usr/bin/env" ]] || ln -s ../../bin/busybox "$SYSROOT/usr/bin/env"
fi
# The dynamic loader looks in /usr/lib: make sure every library is there.
if [[ -d "$SYSROOT/usr/lib64" ]]; then mkdir -p "$SYSROOT/usr/lib"; cp -n "$SYSROOT"/usr/lib64/* "$SYSROOT/usr/lib/" 2>/dev/null || true; fi

# The dynamic linker's cache for the image's own libraries (Steam's container tools read
# it to find the graphics drivers).
if [[ -x /usr/bin/ldconfig && -f "$SYSROOT/etc/ld.so.conf" ]]; then
    ldconfig -r "$SYSROOT" -X 2>/dev/null || true
    [[ -f "$SYSROOT/etc/ld.so.cache" ]] && { mkdir -p "$SYSROOT/var/cache/ldconfig"; ln -sf ../../../etc/ld.so.cache "$SYSROOT/var/cache/ldconfig/ld.so.cache"; }
fi

"$ROOT/scripts/mkimage.sh" "$IMAGE" "${NOVA_CMDLINE:-}" || fail "image creation failed (log: $BUILD_LOG)"
log "Image ready: $IMAGE (build log: $BUILD_LOG)"
